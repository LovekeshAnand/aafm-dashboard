#!/usr/bin/env sh
# Writes deploy/nginx/cloudflare-real-ip.conf from Cloudflare's published IP ranges
# (https://www.cloudflare.com/ips/). Nginx trusts CF-Connecting-IP only from these addresses.
# Run at setup and monthly (cron); then: docker compose exec nginx nginx -s reload
set -eu
cd "$(dirname "$0")/.."
out=nginx/cloudflare-real-ip.conf
tmp=$(mktemp)
{
  echo "# Generated by scripts/update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
      [ -n "$range" ] && echo "set_real_ip_from $range;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"
# Refuse to install a list that came back empty (a failed download must not disable the check).
count=$(grep -c '^set_real_ip_from' "$tmp" || true)
if [ "$count" -lt 10 ]; then
  echo "only $count ranges downloaded; keeping the old list" >&2
  rm -f "$tmp"
  exit 1
fi
mv "$tmp" "$out"
echo "wrote $out ($count ranges)"
